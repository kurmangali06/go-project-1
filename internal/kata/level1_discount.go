package kata

// УРОВЕНЬ 1 — простая проверка значения.
//
// Discount возвращает цену со скидкой.
//
// Контракт:
//   - percent == 0   → цена не меняется
//   - percent == 100 → 0
//   - percent > 100  → 0 (скидка больше цены невозможна)
//   - дробная часть отбрасывается вниз: Discount(999, 10) == 899
//
// Задача: написать тест, который проверяет контракт. Один из пунктов нарушен.
func Discount(price uint32, percent uint8) uint32 {
	if percent >= 100 {
		return 0
	}
	return price * uint32(100-percent) / 100
}
